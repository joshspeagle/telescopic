def burn_in() -> str:
    """Three densities of X_t, stacked, each over the target's outline, with an arrow
    from the target's mean, 0, to the mean of X_t."""
    name, times = "burn-in", [0, 5, 10]
    grid, density, means, sds = laws()
    offsets = means[times]
    check(
        np.all(np.diff(offsets) < 0) and offsets[-1] > 0,
        name,
        "the mean of X_t shrinks at each drawn time and is not zero",
    )
    width, row, top = 640.0, 92.0, 22.0
    x = Scale(-4.0, 9.0, 92.0, 590.0)
    # Every fourth point of the grid, 0.08 apart, draws the curves.
    keep = (grid >= -4.0) & (grid <= 9.0) & (np.arange(len(grid)) % 4 == 0)
    target = stats.norm.pdf(grid[keep])
    height_of = 66.0 / target.max()
    rule = FIGURE["rule"]
    body = [
        segment(float(x(0)), top, float(x(0)), top + 3 * row + 4, MUTED, width=rule, dash="3 4")
    ]
    for i, t in enumerate(times):
        base = top + (i + 1) * row
        curve = np.column_stack([x(grid[keep]), base - density[t][keep] * height_of])
        outline = np.column_stack([x(grid[keep]), base - target * height_of])
        area = np.vstack([[x(-4.0), base], curve, [x(9.0), base]])
        body += [
            f'<path d="{_path(area)} Z" fill="{CX}" fill-opacity="{FIGURE["area"]}"/>',
            _stroke(outline, MUTED, FIGURE["outline"]),
            _stroke(curve, CX, FIGURE["chain"]),
            segment(float(x(-4.0)), base, float(x(9.0)), base, LINE, width=rule),
            text(16, base - 8, rich(("t", ""), f" = {t}")),
            arrow(float(x(0)), base - 76, float(x(means[t])), base - 76, INK),
            text(
                float(x(means[t])) + 8,
                base - 71,
                rich("mean of ", ("X", "t"), f" = {means[t]:.2f}"),
            ),
        ]
    axis = top + 3 * row
    body += [
        segment(float(x(v)), axis, float(x(v)), axis + 5, MUTED, width=rule)
        for v in range(-4, 10, 2)
    ]
    body += [
        text(float(x(v)), axis + 20, f"{v:g}".replace("-", MINUS), "middle", MUTED)
        for v in range(-4, 10, 2)
    ]
    body.append(text(float(x(9.0)), axis + 38, rich(("x", "")), "end", MUTED))
    body.append(text(float(x(0)) - 6, axis + 38, "target mean", "end", MUTED))
    label = (
        "Three curves stacked from top to bottom, the density of X_t at t = 0, 5 and 10 for "
        "random-walk Metropolis started from N(5, 1), each over the gray outline of the "
        "N(0, 1) target; their standard deviations are "
        + ", ".join(f"{sds[t]:.2f}" for t in times)
        + ". An arrow from 0 to the mean of X_t reads "
        + ", ".join(f"{means[t]:.2f} at t = {t}" for t in times)
        + ": smaller at each time, and not zero."
    )
    return svg(width, axis + 48, label, "".join(body))


def two_chains() -> str:
    """V1: X_t solid and Y_{t-L} dashed against t, joined at tau; the times k to m shaded
    as averaged and k + L to tau hatched as the bias correction; the target's density on
    its side at the right."""
    k, m, lag = 5, 20, LAG
    x_path, y_path, tau = first(lambda tau: k + lag + 3 <= tau <= m - 3, "two-chains")
    width, height = 640.0, 330.0
    end = m + 2
    t = Scale(0.0, end, 88.0, 540.0)
    values = np.concatenate([x_path[: end + 1], y_path])
    lo, hi = min(-3.0, values.min() - 0.5), values.max() + 0.5
    v = Scale(lo, hi, 262.0, 56.0)
    band_top, band_bottom = 30.0, 266.0
    times = np.arange(end + 1)
    rule = FIGURE["rule"]
    hatch = (
        '<pattern id="two-chains-hatch" width="7" height="7" patternUnits="userSpaceOnUse" '
        f'patternTransform="rotate(45)"><path d="M0 0V7" stroke="{INK}" '
        f'stroke-opacity="{FIGURE["hatch"]}" stroke-width="{FIGURE["outline"]}"/></pattern>'
    )
    body = [
        f"<defs>{hatch}</defs>",
        (
            f'<rect x="{_f(t(k))}" y="{_f(band_top)}" width="{_f(t(m) - t(k))}" '
            f'height="{_f(band_bottom - band_top)}" fill="{LINE}" '
            f'fill-opacity="{FIGURE["band"]}"/>'
        ),
        (
            f'<rect x="{_f(t(k + lag))}" y="{_f(band_top)}" width="{_f(t(tau) - t(k + lag))}" '
            f'height="{_f(band_bottom - band_top)}" fill="url(#two-chains-hatch)"/>'
        ),
        text(float(t(m)) - 6, band_top + 17, "averaged", "end"),
        text(float(t(k + lag)) + 4, band_top - 8, "bias correction"),
        text(20, band_top - 8, rich(("X", "t"), " and ", ("Y", f"t{MINUS}L")), "start", MUTED),
    ]
    # The target's density on its side, at the right edge, on the vertical scale of the
    # chains.
    grid = np.linspace(lo, hi, 161)
    left = 566.0
    side = np.column_stack([left + stats.norm.pdf(grid) * 60.0 / stats.norm.pdf(0), v(grid)])
    body += [
        f'<path d="{_path(np.vstack([[left, v(lo)], side, [left, v(hi)]]))} Z" fill="{LINE}"/>',
        segment(left, float(v(lo)), left, float(v(hi)), MUTED, width=rule),
        text(left + 4, float(v(hi)) - 6, rich(("π", ""))),
    ]
    met = np.column_stack([t(times[tau : m + 1]), v(x_path[tau : m + 1])])
    chain_x = np.column_stack([t(times[: tau + 1]), v(x_path[: tau + 1])])
    chain_y = np.column_stack([t(times[lag : tau + 1]), v(y_path)])
    body += [
        _stroke(met, MET, FIGURE["chain"]),
        _stroke(chain_y, CY, FIGURE["chain"], dash="7 6"),
        _stroke(chain_x, CX, FIGURE["chain"]),
        dot(float(t(tau)), float(v(x_path[tau])), MET, r=FIGURE["meeting"], ring=True),
        text(float(chain_x[0, 0]), float(chain_x[0, 1]) - 10, rich(("X", "")), "start", CX),
        text(float(chain_y[0, 0]), float(chain_y[0, 1]) - 10, rich(("Y", "")), "start", CY),
    ]
    # The state axis at the left, with a tick at every even value in the drawn range.
    axis_x = 64.0
    body.append(segment(axis_x, float(v(lo)), axis_x, float(v(hi)), MUTED, width=rule))
    for value in range(int(np.ceil(lo / 2)) * 2, int(hi) + 1, 2):
        y = float(v(value))
        body.append(segment(axis_x - 5, y, axis_x, y, MUTED, width=rule))
        body.append(text(axis_x - 9, y + 6, f"{value:g}".replace("-", MINUS), "end", MUTED))
    marks = {
        0: "0",
        k: rich(("k", "")),
        k + lag: rich(("k", ""), " + ", ("L", "")),
        tau: rich(("τ", "")),
        m: rich(("m", "")),
    }
    body.append(time_axis(t, band_bottom + 10, range(end + 1), marks))
    body.append(text(float(t(end)), band_bottom + 52, rich(("t", "")), "end", MUTED))
    label = (
        f"Two chains against time t. Chain X, solid magenta, starts at {x_path[0]:.1f}; chain Y, "
        f"dashed teal, starts at {y_path[0]:.1f} and is drawn {lag} steps to the right, at "
        f"Y_(t-{lag}). The target's density is drawn on its side at the right. The dashed line "
        f"joins the solid one at a dot at t = tau = {tau}, at {x_path[tau]:.1f}, and one dark "
        f"line continues to t = m = {m}. The times from k = {k} to m are shaded and labeled "
        f"averaged; the times from k + L = {k + lag} to tau are hatched and labeled bias "
        f"correction."
    )
    return svg(width, height, label, "".join(body))


def reflection() -> str:
    """V3, static: the proposal densities N(mu_x, I) and N(mu_y, I) in whitened
    coordinates as two filled discs that overprint where they overlap, the mirror line,
    one draw that the coupling reflects and one that it makes identical."""
    name, delta = "reflection", 1.5
    mu_x, mu_y = np.array([[-delta / 2, 0.0]] * 2), np.array([[delta / 2, 0.0]] * 2)
    eye = np.eye(2)
    draws = testing.fixed_draws(normals=[[-0.8, 0.9], [0.3, -1.1]], uniforms=[[0.5], [0.3]])
    xs, ys, identical = couplings.reflection_maximal(mu_x, mu_y, eye, eye, draws)
    check(identical.tolist() == [False, True], name, "the first draw reflected, the second met")
    # The mirror line is x = 0; the caption says that the first draw falls where X's
    # density is far above Y's, and the second inside both outer contours.
    ratio = np.exp(np.sum(stats.norm.logpdf(xs[0] - mu_y[0]) - stats.norm.logpdf(xs[0] - mu_x[0])))
    check(xs[0, 0] < 0 < ys[0, 0] and ratio < 0.2, name, "x' left of the line, far from mu_y")
    inside = np.linalg.norm(xs[1] - mu_x[0]) < 2 and np.linalg.norm(xs[1] - mu_y[0]) < 2
    check(inside, name, "the identical draw inside both outer contours")
    p_meet = 2 * stats.norm.cdf(-delta / 2)
    width, height = 640.0, 356.0
    unit = 52.0
    cx0, cy0 = 330.0, 176.0

    def at(p: np.ndarray) -> tuple[float, float]:
        return cx0 + p[0] * unit, cy0 - p[1] * unit

    body = []
    for mu, color in ((mu_x[0], CX), (mu_y[0], CY)):
        px, py = at(mu)
        body.append(
            f'<circle cx="{_f(px)}" cy="{_f(py)}" r="{_f(2 * unit)}" fill="{color}" '
            f'fill-opacity="{FIGURE["disc"]}" style="mix-blend-mode: {BLEND[0]}"/>'
        )
        for r in (1, 2):
            body.append(
                f'<circle cx="{_f(px)}" cy="{_f(py)}" r="{_f(r * unit)}" fill="none" '
                f'stroke="{color}" stroke-width="{FIGURE["outline"]}"/>'
            )
        body.append(dot(px, py, color, r=FIGURE["center"]))
    (ax, ay), (bx, by) = at(mu_x[0]), at(mu_y[0])
    body += [
        # Below the discs, clear of the contours.
        text(ax - 14, ay + 2 * unit + 26, rich(("μ", "x")), "middle", CX),
        text(bx + 14, by + 2 * unit + 26, rich(("μ", "y")), "middle", CY),
        segment(cx0, 60.0, cx0, height - 26.0, INK, width=FIGURE["outline"], dash="5 4"),
        text(cx0, height - 6, "mirror line", "middle", MUTED),
    ]
    (x1, y1), (x2, y2) = at(xs[0]), at(ys[0])
    body += [
        segment(x1, y1, x2, y2, MUTED, width=FIGURE["rule"], dash="2 3"),
        dot(x1, y1, CX),
        dot(x2, y2, CY),
        text(x1 - 8, y1 - 8, rich(("x", ""), PRIME), "end", CX),
        text(x2 + 8, y2 - 8, rich(("y", ""), PRIME), "start", CY),
    ]
    (x3, y3) = at(xs[1])
    body += [
        dot(x3, y3, MET, r=FIGURE["meeting"], ring=True),
        text(x3 - 84, y3 + 5, rich(("x", ""), f"{PRIME} = ", ("y", ""), PRIME)),
        text(20, 26, rich(("δ", ""), f" = {delta:g}: the proposals coincide")),
        text(20, 49, rich(f"with probability 2Φ({MINUS}", ("δ", ""), f"/2) = {p_meet:.3f}")),
    ]
    label = (
        f"Two overlapping discs, the proposal densities of chain X, magenta, centered at mu_x, "
        f"and of chain Y, teal, centered at mu_y, {delta:g} apart, with contours at 1 and 2 "
        f"standard deviations; where they overlap the colors overprint. A dashed vertical "
        f"mirror line runs halfway between the centers. One draw x' on the left of the line "
        f"is reflected across it to y'. A second draw, inside both outer contours, is one "
        f"dark point labeled x' = y'. Text: the proposals coincide with probability "
        f"2 Phi(-delta/2) = {p_meet:.3f}."
    )
    return svg(width, height, label, "".join(body))


def telescoping() -> str:
    """V2: E[h(X_{k+jL})] for h(x) = x approaching pi(h) = 0, arrows labeled
    E[Delta_{k+jL}] between successive points; below, one replicate's Delta_{k+jL}, zero
    from tau on."""
    name, k, lag, steps = "telescoping", 2, LAG, 7
    at = k + lag * np.arange(steps + 1)
    _, _, means, _ = laws()
    check(np.all(np.diff(means[at]) < 0) and means[at[-1]] > 0, name, "the points fall to 0")
