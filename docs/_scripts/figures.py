from telescopic.tuning import OPTIMAL_SCALE

OUT = DOCS / "_static" / "figures"
GENERATED = "Generated by docs/_scripts/figures.py; edit the figure there."
LIGHT = {name: value[0] for name, value in TOKENS.items()}
CX, CY, MET, INK, MUTED, LINE = (LIGHT[n] for n in ("cx", "cy", "met", "ink", "muted", "line"))
BLUE = CATEGORICAL[0]
UPRIGHT = "ΔΦ"  # capital Greek letters are set upright, as in the theory's equations
MINUS, PRIME = "\u2212", "\u2032"
SIZE = 14  # px of the text in the 640-wide box; subscripts are SIZE * 0.75

# The setting of the tutorial How it works: the target N(0, 1), random-walk Metropolis
# with its default proposal N(x, OPTIMAL_SCALE^2) for cov=[[1.0]], and chains started from
# N(5, 1).
START_MEAN = 5.0
SEED = 0
CANDIDATES = 32  # replicates searched for the first that the rule of a figure accepts


# --------------------------------------------------------------------------- drawing


def rich(*parts: str | tuple[str, str]) -> str:
    """Text and italic symbols: a tuple (base, subscript) sets the base in italic and the
    subscript lowered and smaller; a string is set as it is."""
    out, lowered = [], False
    for part in parts:
        if isinstance(part, tuple):
            base, sub = part
            back = f' dy="{_f(-0.3 * SIZE)}"' if lowered else ""
            style = "" if base in UPRIGHT else ' font-style="italic"'
            out.append(f"<tspan{style}{back}>{base}</tspan>")
            lowered = bool(sub)
            if sub:
                out.append(
                    f'<tspan dy="{_f(0.3 * SIZE)}" font-size="0.75em" font-style="italic">'
                    f"{sub}</tspan>"
                )
        else:
            # No-break spaces, which a renderer cannot collapse at the edge of a tspan.
            part = part.replace(" ", "\u00a0")
            back = f' dy="{_f(-0.3 * SIZE)}"' if lowered else ""
            out.append(f"<tspan{back}>{part}</tspan>" if back else part)
            lowered = False
    return "".join(out)


def text(x: float, y: float, content: str, anchor: str = "start", color: str = INK) -> str:
    fill = "" if color == INK else f' fill="{color}"'
    return f'<text x="{_f(x)}" y="{_f(y)}" text-anchor="{anchor}"{fill}>{content}</text>'


def line(points: np.ndarray, color: str, width: float = 2.5, dash: str = "") -> str:
    dashes = f' stroke-dasharray="{dash}"' if dash else ""
    return (
        f'<path d="{_path(points)}" fill="none" stroke="{color}" stroke-width="{_f(width)}" '
        f'stroke-linejoin="round" stroke-linecap="round"{dashes}/>'
    )


def segment(
    x1: float, y1: float, x2: float, y2: float, color: str, width: float = 2.5, dash: str = ""
) -> str:
    return line(np.array([[x1, y1], [x2, y2]]), color, width, dash)


def arrow(x1: float, y1: float, x2: float, y2: float, color: str, width: float = 2.0) -> str:
    """A line from (x1, y1) to (x2, y2) with a head at the end; a head alone when the line
    is shorter than the head."""
    length = np.hypot(x2 - x1, y2 - y1)
    if length == 0:
        return ""
    ux, uy = (x2 - x1) / length, (y2 - y1) / length
    head = min(9.0, length)
    bx, by = x2 - ux * head, y2 - uy * head
    wing = head * 0.5
    tip = np.array([[x2, y2], [bx - uy * wing, by + ux * wing], [bx + uy * wing, by - ux * wing]])
    shaft = segment(x1, y1, bx, by, color, width=width) if length > head else ""
    return shaft + f'<path d="{_path(tip)} Z" fill="{color}"/>'


def dot(x: float, y: float, color: str, r: float = 4.5, ring: bool = False) -> str:
    stroke = f' stroke="{FIGURE_GROUND}" stroke-width="1.5"' if ring else ""
    return f'<circle cx="{_f(x)}" cy="{_f(y)}" r="{_f(r)}" fill="{color}"{stroke}/>'


def svg(width: float, height: float, label: str, body: str) -> str:
    return (
        f"<!-- {GENERATED} -->\n"
        f'<svg viewBox="0 0 {_f(width)} {_f(height)}" role="img" aria-label="{label}" '
        f'font-family="{FONTS["text"][4]}" font-size="{SIZE}" fill="{INK}">'
        f'<rect width="{_f(width)}" height="{_f(height)}" fill="{FIGURE_GROUND}"/>'
        f"{body}</svg>\n"
    )


class Scale:
    """A linear map from data to the box: lo and hi of the data to a and b."""

    def __init__(self, lo: float, hi: float, a: float, b: float) -> None:
        self.lo, self.slope, self.a = lo, (b - a) / (hi - lo), a

    def __call__(self, v: npt.ArrayLike) -> np.ndarray:
        return self.a + (np.asarray(v, dtype=float) - self.lo) * self.slope


def time_axis(t: Scale, y: float, ticks: range, labels: dict[int, str]) -> str:
    """A time axis at height y: a tick at every integer of ticks, and a label under each
    tick of labels."""
    out = [segment(float(t(ticks[0])), y, float(t(ticks[-1])), y, MUTED, width=1)]
    for s in ticks:
        out.append(
            segment(float(t(s)), y, float(t(s)), y + (6 if s in labels else 3), MUTED, width=1)
        )
    out += [text(float(t(s)), y + 21, labels[s], "middle", MUTED) for s in labels]
    return "".join(out)


# --------------------------------------------------------------------------- the numbers


def laws(times: int) -> tuple[np.ndarray, np.ndarray]:
    """The density of X_t for t = 0, ..., times on a grid, for random-walk Metropolis on
    N(0, 1) started from N(START_MEAN, 1): the transition is the proposal's density times
    the acceptance probability off the diagonal, and the rejection on it."""
    h = 0.02
    grid = np.arange(-8.0, 13.0 + h / 2, h)
    log_target = -0.5 * grid**2
    kernel = stats.norm.pdf(grid[None, :] - grid[:, None], scale=OPTIMAL_SCALE) * h
    kernel *= np.minimum(1.0, np.exp(log_target[None, :] - log_target[:, None]))
    np.fill_diagonal(kernel, 0.0)
    kernel[np.diag_indices_from(kernel)] = 1.0 - kernel.sum(axis=1)
    law = stats.norm.pdf(grid, START_MEAN, 1.0) * h
    out = [law]
    for _ in range(times):
        law = law @ kernel
        out.append(law)
    return grid, np.array(out) / h


def pairs(k: int, m: int, lag: int) -> engine.Replicates:
    """Coupled pairs of the tutorial's setting, run by the package, with their paths."""
    target = telescopic.Target(lambda x: -0.5 * x[:, 0] ** 2, vectorize=True)
    kernel = telescopic.kernels.RandomWalk(cov=[[1.0]])
    init = telescopic.initial.Normal(mean=[START_MEAN], cov=[1.0])
    return engine.run(
        target, kernel, init, range(CANDIDATES), k=k, m=m, lag=lag, rng=SEED, keep_paths=True
    )


def first(
    runs: engine.Replicates, rule: Callable[[int], bool]
) -> tuple[np.ndarray, np.ndarray, int]:
    """The paths and meeting time of the first replicate, by index, whose meeting time
    the rule accepts."""
    i = next(i for i in runs.index if rule(int(runs.meeting_time[i])))
    x, y = (path[:, 0] for path in runs.paths[i])
    return x, y, int(runs.meeting_time[i])


