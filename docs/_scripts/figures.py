@functools.cache
def laws() -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """The grid, and the density, mean and standard deviation of X_t on it for
    t = 0, ..., LAST, for random-walk Metropolis on N(0, 1) started from
    N(START_MEAN, 1): the transition is the proposal's density times the acceptance
    probability off the diagonal, and the rejection on it."""
    h = 0.02
    grid = np.arange(-8.0, 13.0 + h / 2, h)
    log_target = -0.5 * grid**2
    kernel = stats.norm.pdf(grid[None, :] - grid[:, None], scale=OPTIMAL_SCALE) * h
    kernel *= np.minimum(1.0, np.exp(log_target[None, :] - log_target[:, None]))
    np.fill_diagonal(kernel, 0.0)
    kernel[np.diag_indices_from(kernel)] = 1.0 - kernel.sum(axis=1)
    law = stats.norm.pdf(grid, START_MEAN, 1.0) * h
    out = [law]
    for _ in range(LAST):
        law = law @ kernel
        out.append(law)
    mass = np.array(out)
    means = mass @ grid
    sds = np.sqrt(mass @ grid**2 - means**2)
    return grid, mass / h, means, sds


@functools.cache
def pairs() -> engine.Replicates:
    """Coupled pairs of the tutorial's setting with the lag LAG, run by the package with a
    target evaluated point by point, with their paths."""
    return engine.run(
        telescopic.Target(log_density),
        kernel(),
        initial(),
        range(CANDIDATES),
        k=0,
        m=LAST,
        lag=LAG,
        rng=SEED,
        keep_paths=True,
    )


def first(rule: Callable[[int], bool], figure: str) -> tuple[np.ndarray, np.ndarray, int]:
    """The paths of X and Y and the meeting time of the first replicate, by index, whose
    meeting time the rule accepts."""
    runs = pairs()
    for i, tau in zip(runs.index.tolist(), runs.meeting_time.tolist(), strict=True):
        if np.isfinite(tau) and rule(int(tau)):
            x, y = (path[:, 0] for path in runs.paths[i])
            check(x[int(tau)] == y[int(tau) - LAG], figure, f"the meeting of replicate {i}")
            return x, y, int(tau)
    raise SystemExit(
        f"{figure}: none of the {CANDIDATES} replicates has a meeting time that the figure "
        "can draw; change SEED or CANDIDATES"
    )


