def rich(*parts: str | tuple[str, str]) -> str:
    """Text and italic symbols: a tuple (base, subscript) sets the base in italic and the
    subscript lowered and smaller; a string is set as it is."""
    out, lowered = [], False
    for part in parts:
        if isinstance(part, tuple):
            base, sub = part
            back = f' dy="{_f(-0.3 * SIZE)}"' if lowered else ""
            style = "" if base in UPRIGHT else ' font-style="italic"'
            out.append(f"<tspan{style}{back}>{base}</tspan>")
            lowered = bool(sub)
            if sub:
                out.append(
                    f'<tspan dy="{_f(0.3 * SIZE)}" font-size="{FIGURE["subscript"]}em" '
                    f'font-style="italic">{sub}</tspan>'
                )
        else:
            # No-break spaces, which a renderer cannot collapse at the edge of a tspan.
            part = part.replace(" ", "\u00a0")
            back = f' dy="{_f(-0.3 * SIZE)}"' if lowered else ""
            out.append(f"<tspan{back}>{part}</tspan>" if back else part)
            lowered = False
    return "".join(out)


def text(x: float, y: float, content: str, anchor: str = "start", color: str = INK) -> str:
    fill = "" if color == INK else f' fill="{color}"'
    return f'<text x="{_f(x)}" y="{_f(y)}" text-anchor="{anchor}"{fill}>{content}</text>'


def segment(
    x1: float,
    y1: float,
    x2: float,
    y2: float,
    color: str,
    width: float = FIGURE["chain"],
    dash: str = "",
) -> str:
    return _stroke(np.array([[x1, y1], [x2, y2]]), color, width, dash=dash)


def arrow(
    x1: float, y1: float, x2: float, y2: float, color: str, width: float = FIGURE["arrow"]
) -> str:
    """A line from (x1, y1) to (x2, y2) with a head at the end; a head alone when the line
    is shorter than the head."""
    length = np.hypot(x2 - x1, y2 - y1)
    if length == 0:
        return ""
    ux, uy = (x2 - x1) / length, (y2 - y1) / length
    head = min(9.0, length)
    bx, by = x2 - ux * head, y2 - uy * head
    wing = head * 0.5
    tip = np.array([[x2, y2], [bx - uy * wing, by + ux * wing], [bx + uy * wing, by - ux * wing]])
    shaft = segment(x1, y1, bx, by, color, width=width) if length > head else ""
    return shaft + f'<path d="{_path(tip)} Z" fill="{color}"/>'


def dot(x: float, y: float, color: str, r: float = FIGURE["dot"], ring: bool = False) -> str:
    stroke = f' stroke="{FIGURE_GROUND}" stroke-width="{FIGURE["outline"]}"' if ring else ""
    return f'<circle cx="{_f(x)}" cy="{_f(y)}" r="{_f(r)}" fill="{color}"{stroke}/>'


def svg(width: float, height: float, label: str, body: str) -> str:
    ground = f'<rect width="{_f(width)}" height="{_f(height)}" fill="{FIGURE_GROUND}"/>'
    style = f' font-family="{FONTS["text"][4]}" font-size="{_f(SIZE)}" fill="{INK}"'
    return _svg(width, height, ground + body, label, NOTE, style)


class Scale:
    """A linear map from data to the box: lo and hi of the data to a and b."""

    def __init__(self, lo: float, hi: float, a: float, b: float) -> None:
        self.lo, self.slope, self.a = lo, (b - a) / (hi - lo), a

    def __call__(self, v: npt.ArrayLike) -> np.ndarray:
        return self.a + (np.asarray(v, dtype=float) - self.lo) * self.slope


def time_axis(t: Scale, y: float, ticks: range, labels: dict[int, str]) -> str:
    """A time axis at height y: a tick at every integer of ticks, and a label under each
    tick of labels."""
    rule = FIGURE["rule"]
    out = [segment(float(t(ticks[0])), y, float(t(ticks[-1])), y, MUTED, width=rule)]
    for s in ticks:
        tick = 6 if s in labels else 3
        out.append(segment(float(t(s)), y, float(t(s)), y + tick, MUTED, width=rule))
    out += [text(float(t(s)), y + 21, labels[s], "middle", MUTED) for s in labels]
    return "".join(out)


def check(holds: bool | np.bool_, figure: str, claim: str) -> None:
    """Stop with a message when a claim of a figure's text no longer holds."""
    if not holds:
        raise SystemExit(f"{figure}: {claim} no longer holds; redraw the figure and its text")


