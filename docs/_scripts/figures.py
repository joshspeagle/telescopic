"""Draw the generated figures of the Concepts pages, as SVG files that the pages inline.

``python docs/_scripts/figures.py`` writes into ``docs/_static/figures/``:

* ``burn-in.svg``: the law of :math:`X_t` of random-walk Metropolis on a standard normal
  target, started from N(5, 1), at three times, computed on a grid;
* ``two-chains.svg`` (V1): one coupled pair run by :func:`telescopic.engine.run`, with the
  averaged times and the times of the bias correction;
* ``reflection.svg`` (V3, a static frame): two draws of
  :func:`telescopic.couplings.reflection_maximal`, one reflected and one identical;
* ``telescoping.svg`` (V2): the expectations :math:`\\mathbb E[h(X_{k+jL})]`, from the same
  grid as ``burn-in.svg``, and one replicate's differences :math:`\\Delta_{k+jL}`.

The figures are drawn on the light figure ground in the colors of ``brand.py``: magenta
for chain X, teal for chain Y, the ink of met chains once they have met, and the plot
colors for the rest. ``{diagram}`` (``docs/_ext/telescopic_theme.py``) inlines them, so
their text is set in the site's faces. ``--check`` writes nothing and exits with 1, naming
each stale file, if a written file differs from what this script would write; CI runs it.
"""

