"""Draw the generated figures of the documentation, as SVG files that the pages inline.

``python docs/_scripts/figures.py`` writes into ``docs/_static/figures/``:

* ``burn-in.svg``: the law of :math:`X_t` of random-walk Metropolis on a standard normal
  target, started from N(5, 1), at three times, computed on a grid;
* ``two-chains.svg`` (V1): one coupled pair run by :func:`telescopic.engine.run`, with the
  averaged times and the times of the bias correction;
* ``reflection.svg`` (V3, a static frame): two draws of
  :func:`telescopic.couplings.reflection_maximal`, one reflected and one identical;
* ``telescoping.svg`` (V2): the expectations :math:`\\mathbb E[h(X_{k+jL})]`, from the same
  grid as ``burn-in.svg``, and one replicate's differences :math:`\\Delta_{k+jL}`;
* ``signed-measure.svg`` (V5): one replicate's atoms and weights, and the signed
  histogram of 1000 replicates run by :func:`telescopic.sample`;
* ``tv-bound.svg`` (V6, a static frame): the survival function of the meeting times of
  1000 pairs run by :class:`telescopic.CoupledSampler`, its values that add up to the
  bound on the total variation distance at one time, and that bound against time;
* ``cost.svg`` (V12): one coupled pair's kernel applications, from the same run as
  ``two-chains.svg``, against the cost that the engine counts;
* ``remedies.svg`` (V11): a chart from each condition that a run reports to the warning or
  error it raises and the remedy that its message names, checked against the messages of
  small runs made to raise them;
* ``pipeline.svg`` (V9): the steps of an automatic run and the arguments that skip them,
  checked against the package's constants and two small runs;
* ``result.svg`` (V13): the attributes of a :class:`telescopic.Result`, checked against a
  small run's, and the methods that read its signed measures and meeting times;
* ``chunks.svg`` (V14): the chunks into which a pool cuts a run's replicate indices, from
  a run on a pool that records them, and each index's own random stream;
* ``hmc-meeting.svg`` (V15): coupled HMC trajectories, which share their momentum, and a
  meeting step, each checked against :class:`telescopic.kernels.HMC`'s coupled step.

The figures are drawn on the light figure ground with the colors, faces, sizes and
helpers of ``brand.py``: magenta for chain X, teal for chain Y, the ink of met chains once
they have met, and the plot colors for the rest. The pairs are run with a target
evaluated point by point, so that they repeat bitwise from the seed, and every claim of
a figure's alternative text or of its caption on the page is checked here: a run that
breaks one stops with a message. ``{diagram}`` (``docs/_ext/telescopic_theme.py``)
inlines the figures, so their text is set in the site's faces. ``--check`` writes nothing
and exits with 1, naming each stale file, if a written file differs from what this script
would write; CI runs it.
"""

