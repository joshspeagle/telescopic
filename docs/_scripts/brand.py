def _f(x: float) -> str:
    return f"{x:.1f}".rstrip("0").rstrip(".")


def _theme(theme: int) -> dict[str, str]:
    return {name: value[theme] for name, value in TOKENS.items()}


def _chain(guide: tuple[tuple[float, float], ...], n: int, jitter: float, rng) -> np.ndarray:
    """``n`` points along a polyline, evenly spaced by arc length, jittered by a normal
    spread that vanishes at both ends; the guide itself when ``n`` is 0."""
    points = np.asarray(guide)
    if n == 0:
        return points
    arc = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(points, axis=0), axis=1))])
    s = np.linspace(0.0, arc[-1], n)
    along = np.column_stack([np.interp(s, arc, points[:, i]) for i in range(2)])
    envelope = np.sin(np.pi * np.linspace(0.0, 1.0, n)) ** 0.6
    return along + rng.normal(size=(n, 2)) * jitter * envelope[:, None]


def _path(points: np.ndarray) -> str:
    return "M" + " L".join(f"{_f(x)} {_f(y)}" for x, y in points)


def _stroke(points: np.ndarray, color: str, width: float, blend: str = "") -> str:
    style = f' style="mix-blend-mode:{blend}"' if blend else ""
    return (
        f'<path d="{_path(points)}" fill="none" stroke="{color}" stroke-width="{width}" '
        f'stroke-linecap="round" stroke-linejoin="round"{style}/>'
    )


def mark_body(cut: str, colors: dict[str, str], blend: str) -> str:
    """The Focus mark's elements in its ``BOX`` square, without an ``<svg>`` wrapper."""
    c = CUTS[cut]
    rng = np.random.default_rng(SEED)
    (n_chain, n_met), (j_chain, j_met) = c["points"], c["jitter"]
    x = _chain(GUIDES["x"], n_chain, j_chain, rng)
    y = _chain(GUIDES["y"], n_chain, j_chain, rng)
    met = _chain(GUIDES["met"], n_met, j_met, rng)
    lens_width, lens_fill = c["lens"]
    body = (
        f'<path d="{LENS}" fill="{colors["ink"]}" fill-opacity="{lens_fill}" '
        f'stroke="{colors["ink"]}" stroke-width="{lens_width}" stroke-linejoin="round"/>'
    )
    body += _stroke(met, colors["met"], c["stroke"])
    if c["eyepiece"]:
        body += (
            f'<path d="{EYEPIECE}" fill="{colors["bg"]}" stroke="{colors["ink"]}" '
            f'stroke-width="{c["eyepiece"]}" stroke-linejoin="round"/>'
        )
    body += _stroke(x, colors["cx"], c["stroke"], blend) + _stroke(
        y, colors["cy"], c["stroke"], blend
    )
    if c["beads"]:
        body += "".join(
            f'<circle cx="{_f(px)}" cy="{_f(py)}" r="{c["beads"]}" fill="{colors["bg"]}"/>'
            for chain in (x, y)
            for px, py in chain[1:-1]
        )
    radius, width = c["ring"]
    if radius:
        body += (
            f'<circle cx="{_f(FOCUS[0])}" cy="{_f(FOCUS[1])}" r="{radius}" fill="{colors["bg"]}" '
            f'stroke="{colors["met"]}" stroke-width="{width}"/>'
        )
    return body


def _svg(width: float, height: float, body: str, label: str | None = "telescopic") -> str:
    aria = f' role="img" aria-label="{label}"' if label else ""
    return (
        f"<!-- {GENERATED} -->\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {_f(width)} {_f(height)}"{aria}>'
        f"{body}</svg>\n"
    )


def mark_svg(cut: str, theme: int) -> str:
    return _svg(BOX, BOX, mark_body(cut, _theme(theme), BLEND[theme]))


def favicon_svg() -> str:
    """The tiny cut, following the browser's color scheme."""
    names = ("bg", "ink", "cx", "cy", "met")
    light, dark = (";".join(f"--{n}:{TOKENS[n][t]}" for n in names) for t in (0, 1))
    style = f"<style>svg{{{light}}}@media (prefers-color-scheme:dark){{svg{{{dark}}}}}</style>"
    colors = {n: f"var(--{n})" for n in names}
    return _svg(BOX, BOX, style + mark_body("tiny", colors, ""), label=None)


# --------------------------------------------------------------------------- the wordmark


@functools.cache
def wordmark() -> tuple[list[tuple[float, str]], float, int, float]:
    """The wordmark in Red Hat Display 800 as SVG paths in font units (y up), placed by
    advance widths with the headings' letter spacing; kerning is not applied. Returns the
    paths with their offsets, the width, the units per em and the x-height."""
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.ttLib import TTFont

    font = TTFont(WORDMARK_FACE)
    glyphs, cmap, metrics = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
    em = font["head"].unitsPerEm
    tracking = TYPE["title"][5] * em
    paths, x = [], 0.0
    for character in WORDMARK:
        name = cmap[ord(character)]
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(pen)
        paths.append((x, pen.getCommands()))
        x += metrics[name][0] + tracking
    return paths, x - tracking, em, font["OS/2"].sxHeight


def lockup_svg(theme: int) -> str:
    """The mid cut beside the wordmark, all outlines; the wordmark's x-height is centered
    on the mark's focus."""
    paths, width, em, x_height = wordmark()
    colors = _theme(theme)
    scale = BOX / MARK_EM / em
    baseline = FOCUS[1] + x_height * scale / 2
    letters = "".join(f'<path transform="translate({_f(x)} 0)" d="{d}"/>' for x, d in paths)
    word = (
        f'<g transform="translate({_f(BOX + GAP)} {_f(baseline)}) scale({scale:.5f} {-scale:.5f})" '
        f'fill="{colors["ink"]}">{letters}</g>'
    )
    body = mark_body("mid", colors, BLEND[theme]) + word
    return _svg(BOX + GAP + width * scale, BOX, body)


# --------------------------------------------------------------------------- the hero


def hero_svg() -> str:
    """The landing page's coupled pair in the Focus composition, colored by the theme's
    classes. The time axis runs left to right: X_t and, as the estimator pairs them,
    Y_{t-L} at time t, until the meeting time tau puts both at the focus; from there one
    line, X_t, continues. One vertical scale, centered on the meeting point, serves both
    chains."""
    data = json.loads(HERO_DATA.read_text(encoding="utf-8"))
    x, y = np.array(data["x"]), np.array(data["y"])
    tau, lag = data["meeting_time"], data["lag"]
    width, height = HERO_BOX
    stretch = width / BOX
    left, focus = GUIDES["x"][0][0] * stretch, FOCUS[0] * stretch
    meeting = x[tau]
    spread = max(np.abs(x - meeting).max(), np.abs(y - meeting).max())
    scale = (FOCUS[1] - GUIDES["x"][0][1] + 30) / spread  # the chains reach 40 units from the edge

    def points(t: np.ndarray, v: np.ndarray) -> np.ndarray:
        return np.column_stack([left + t * (focus - left) / tau, FOCUS[1] - (v - meeting) * scale])

    t = np.arange(len(x))
    chain_x = points(t[: tau + 1], x[: tau + 1])
    chain_y = points(t[lag : tau + 1], y)
    merged = points(t[tau:], x[tau:])

    def line(p: np.ndarray, cls: str) -> str:
        return f'<path class="{cls}" d="{_path(p)}"/>'

    def shifted(d: str, at: float) -> str:
        return (
            f'<path class="hero-lens" transform="translate({_f(at * stretch - at)} 0)" d="{d}"/>'
        )

    label = (
        f"One coupled pair of chains on a standard normal target. Chain X, in magenta, starts "
        f"at {x[0]:.1f} and chain Y, in teal, at {y[0]:.1f}; they meet at step {tau}, at "
        f"{meeting:.2f}, and continue as one line."
    )
    sx, sy = chain_x[0], chain_y[0]
    body = (
        f'<clipPath id="hero-reveal"><rect class="hero-reveal" width="{_f(width)}" '
        f'height="{_f(height)}"/></clipPath>'
        + shifted(LENS, 62)
        + shifted(EYEPIECE, 216)
        + '<g clip-path="url(#hero-reveal)" fill="none" stroke-linecap="round" '
        f'stroke-linejoin="round" stroke-width="{HERO_STROKE}">'
        + line(merged, "hero-met")
        + line(chain_x, "hero-x")
        + line(chain_y, "hero-y")
        + f'<path class="hero-tick" d="M{_f(focus)} {_f(FOCUS[1] + 12)}V{_f(height - 24)}"/>'
        + f'<circle class="hero-ring" cx="{_f(focus)}" cy="{_f(FOCUS[1])}" r="7"/>'
        + f'<text class="hero-label" x="{_f(focus)}" y="{_f(height - 4)}" '
        f'text-anchor="middle">met at step {tau}</text>'
        + "</g>"
        + f'<text class="hero-label" x="{_f(sx[0])}" y="{_f(sx[1] - 12)}">X</text>'
        + f'<text class="hero-label" x="{_f(sy[0])}" y="{_f(sy[1] + 24)}">Y</text>'
    )
    return (
        f"<!-- {GENERATED} -->\n"
        f'<svg class="hero-pair" viewBox="0 0 {_f(width)} {_f(height)}" role="img" '
        f'aria-label="{label}">{body}</svg>\n'
    )


