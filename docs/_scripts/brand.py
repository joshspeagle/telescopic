def tokens_css() -> str:
    def colors(theme: int) -> str:
        lines = [f"  --t-{name}: {value[theme]};" for name, value in TOKENS.items()]
        lines.append(f"  --t-blend: {BLEND[theme]};")
        lines.append(f"  color-scheme: {('light', 'dark')[theme]};")
        return "\n".join(lines)

    fixed = [f"  --t-font-{role}: {font[5]};" for role, font in FONTS.items()]
    for name, (_, face, weight, px, height, tracking) in TYPE.items():
        fixed.append(f"  --t-type-{name}: {weight} {_f(px)}px/{height} var(--t-font-{face});")
        if tracking:
            fixed.append(f"  --t-tracking-{name}: {tracking}em;")
    fixed += [f"  --t-{name}: {value}px;" for name, (value, _) in SIZES.items()]
    fixed.append(f"  --t-figure-ground: {FIGURE_GROUND};")
    dark = colors(1)
    return (
        f"/* {GENERATED} */\n"
        f":root {{\n{colors(0)}\n" + "\n".join(fixed) + "\n}\n"
        f'@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme="light"]) {{\n'
        f"{dark}\n  }}\n}}\n"
        f':root[data-theme="dark"] {{\n{dark}\n}}\n'
    )


def face_file(package: str, weight: int, style: str) -> str:
    return f"{package}-latin-{weight}-{style}.woff2"


def fonts_css() -> str:
    faces = [
        f"@font-face {{\n  font-family: '{family}';\n  font-style: {style};\n"
        f"  font-weight: {weight};\n  font-display: swap;\n"
        f"  src: url({face_file(package, weight, style)}) format('woff2');\n"
        f"  unicode-range: {LATIN};\n}}"
        for family, package, _, _, faces, _ in FONTS.values()
        for weight, style in faces
    ]
    return f"/* {GENERATED} */\n" + "\n".join(faces) + "\n"


def matplotlibrc() -> str:
    """Plots of the executed pages: drawn on the light figure ground in both themes, text
    in ink, axes in muted, series in the categorical colors."""
    light = {name: value[0].lstrip("#") for name, value in TOKENS.items()}
    cycle = ", ".join(f"'{c.lstrip('#')}'" for c in CATEGORICAL)
    settings = {
        "figure.dpi": 144,
        "figure.facecolor": FIGURE_GROUND.lstrip("#"),
        "axes.facecolor": FIGURE_GROUND.lstrip("#"),
        "savefig.facecolor": FIGURE_GROUND.lstrip("#"),
        "figure.constrained_layout.use": True,
        "axes.prop_cycle": f"cycler('color', [{cycle}])",
        "text.color": light["ink"],
        "axes.labelcolor": light["ink"],
        "axes.edgecolor": light["muted"],
        "xtick.color": light["muted"],
        "ytick.color": light["muted"],
        "grid.color": light["line"],
        "axes.spines.top": False,
        "axes.spines.right": False,
        "legend.frameon": False,
        "font.size": 11,
        "lines.linewidth": 1.8,
    }
    return f"# {GENERATED}\n" + "".join(f"{k}: {v}\n" for k, v in settings.items())


# --------------------------------------------------------------------------- checks and tables


def _luminance(color: str) -> float:
    channels = [int(color[i : i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(a: str, b: str) -> float:
    """The WCAG 2 contrast ratio of two colors."""
    high, low = sorted((_luminance(a), _luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def contrast_problems() -> list[str]:
    problems = []
    for theme, mode in enumerate(("light", "dark")):
        for name, least in MINIMUM.items():
            for ground in ("bg", "surface"):
                ratio = contrast(TOKENS[name][theme], TOKENS[ground][theme])
                if ratio < least:
                    problems.append(f"{name} on {ground} ({mode}) is {ratio:.2f}, below {least}")
    problems += [
        f"categorical {c} on the figure ground is {contrast(c, FIGURE_GROUND):.2f}, below 3"
        for c in CATEGORICAL
        if contrast(c, FIGURE_GROUND) < 3
    ]
    return problems


def tables() -> dict[str, str]:
    """The generated tables of brand.md, by marker name."""
    colors = [
        "| Token | Role | Light | on `bg` | on `surface` | Dark | on `bg` | on `surface` |",
        "|---" * 8 + "|",
    ]
    for name, (light, dark, role) in TOKENS.items():
        cells = []
        for theme, value in enumerate((light, dark)):
            ratios = (
                [f"{contrast(value, TOKENS[g][theme]):.2f}" for g in ("bg", "surface")]
                if name not in ("bg", "surface")
                else ["", ""]
            )
            cells.append(f"`{value}` | " + " | ".join(ratios))
        colors.append(f"| `{name}` | {role} | " + " | ".join(cells) + " |")
    plots = ["| Slot | Color | on the figure ground |", "|---|---|---|"]
    plots += [
        f"| {i} | `{c}` | {contrast(c, FIGURE_GROUND):.2f} |" for i, c in enumerate(CATEGORICAL)
    ]
    names = list(CUTS)
    cuts = ["| Cut | Used at | Chain stroke | Detail | Files |", "|---|---|---|---|---|"]
    for i, (name, c) in enumerate(CUTS.items()):
        upper = CUTS[names[i - 1]]["px"] if i else None
        used = (
            f"{c['px']} px and up"
            if upper is None
            else (f"below {upper} px" if c["px"] == 0 else f"{c['px']} to {upper - 1} px")
        )
        detail = ", ".join(
            part
            for part, present in (
                ("jittered steps", c["points"][0]),
                ("step beads", c["beads"]),
                ("eyepiece", c["eyepiece"]),
                ("meeting ring", c["ring"][0]),
            )
            if present
        )
        cuts.append(
            f"| {name} | {used} | {c['stroke']} | {detail or 'straight chains, lens only'} "
            f"| `brand/mark-{name}-{{light,dark}}.svg` |"
        )
    type_rows = [
        "| Role | Face | Weight | Size | Line height | Letter spacing |",
        "|---" * 6 + "|",
    ]
    for role, face, weight, px, height, tracking in TYPE.values():
        spacing = f"{tracking} em" if tracking else "0"
        type_rows.append(
            f"| {role} | {FONTS[face][0]} | {weight} | {_f(px)} px | {height} | {spacing} |"
        )
    sizes = ["| Size | Value | Use |", "|---|---|---|"]
    sizes += [f"| `{name}` | {value} px | {use} |" for name, (value, use) in SIZES.items()]
    sizes.append(f"| mark : wordmark | {MARK_EM:.3f} | the mark's height over the type size |")
    return {
        "colors": "\n".join(colors),
        "plots": "\n".join(plots),
        "cuts": "\n".join(cuts),
        "type": "\n".join(type_rows),
        "sizes": "\n".join(sizes),
    }


def outputs() -> dict[Path, str]:
    brand = STATIC / "brand"
    out = {
        STATIC / "tokens.css": tokens_css(),
        FONT_DIR / "fonts.css": fonts_css(),
        brand / "favicon.svg": favicon_svg(),
        THEME / "hero.svg": hero_svg(),
        DOCS / "matplotlibrc": matplotlibrc(),
    }
    for theme, mode in enumerate(("light", "dark")):
        for cut in CUTS:
            out[brand / f"mark-{cut}-{mode}.svg"] = mark_svg(cut, theme)
        out[brand / f"lockup-{mode}.svg"] = lockup_svg(theme)
    text = BRAND_MD.read_text(encoding="utf-8")
    for name, table in tables().items():
        start, end = f"<!-- {name}:start -->", f"<!-- {name}:end -->"
        i, j = text.index(start) + len(start), text.index(end)
        text = text[:i] + "\n" + table + "\n" + text[j:]
    out[BRAND_MD] = text
    return out


def font_problems() -> list[str]:
    files = [
        face_file(package, weight, style)
        for _, package, _, _, faces, _ in FONTS.values()
        for weight, style in faces
    ]
    files += [f"OFL-{font[1]}.txt" for font in FONTS.values()]
    return [
        f"docs/_themes/telescopic/static/fonts/{name} is missing (run docs/_scripts/fetch_fonts.py)"
        for name in files
        if not (FONT_DIR / name).exists()
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a written file is stale")
    args = parser.parse_args(argv)
    problems = contrast_problems() + font_problems()
    if problems:
        print(*problems, sep="\n")
        return 1
    stale = []
    for path, text in outputs().items():
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(f"{path.relative_to(DOCS.parent)} is stale (run docs/_scripts/brand.py)")
    if stale:
        print(*stale, sep="\n")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
