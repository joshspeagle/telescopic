"""The identity of the telescopic documentation: its numbers, and the files written from them.

``docs/design/brand.md`` explains the design; every color, size and font it quotes is
defined here. ``python docs/_scripts/brand.py`` writes

* into ``docs/_themes/telescopic/static/``: ``tokens.css`` (colors, type and sizes of the
  theme), ``fonts/fonts.css`` (the faces that ``fetch_fonts.py`` downloads), and in
  ``brand/`` the Focus mark in three cuts for light and dark grounds, the favicon and the
  lockups, whose wordmark is drawn as outlines;
* ``docs/_themes/telescopic/hero.svg``, the landing page's coupled pair, drawn from
  ``hero_pair.json``;
* ``docs/matplotlibrc``, the style of every executed page's plots;
* the generated tables of ``brand.md``, between its ``<!-- name:start -->`` and
  ``<!-- name:end -->`` markers.

``--check`` writes nothing and exits with 1, naming each stale file, if a written file
differs from what this script would write, or if a font file is missing. Either way the
script refuses a token whose contrast falls below its minimum. CI runs the check.
"""

